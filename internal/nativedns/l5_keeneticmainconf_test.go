// TestAdoptKeeneticReadsTheMainConfig (L5): the card that shows what the router actually serves read
// the one file that does not hold it.
//
// On Entware the upstream chain lives in /opt/etc/dnsmasq.conf, which ends with
// conf-dir=/opt/etc/dnsmasq.d,*.conf; the conf-dir is where WayHop drops its own ipset policy file.
// AdoptKeenetic read only the conf-dir. Measured on a live Keenetic: dnsmasq running and
// owning :53, main config carrying no-resolv, strict-order, server=1.1.1.1 and server=8.8.8.8, and
// dnsmasq.d holding exactly one file — WayHop's policy, with zero server= lines. The page therefore
// said "No upstreams detected" about a resolver forwarding every LAN lookup to two plaintext
// servers, and the write-back preview would have described a plane with neither strict-order nor
// no-resolv set.
func TestAdoptKeeneticReadsTheMainConfig(t *testing.T) {
	var asked string
	run := func(name string, args ...string) (string, error) {
		cmd := strings.Join(args, " ")
		if strings.Contains(cmd, "dnsmasq") {
			asked = cmd
			// Answer the way `cat main confdir/*` does: main first, then the conf-dir.
			return "no-resolv\nstrict-order\nserver=1.1.1.1\nserver=8.8.8.8\n" +
				"conf-dir=/opt/etc/dnsmasq.d,*.conf\n" +
				"# Generated by WayHop\nipset=/github.com/wr_list_rl_github_4\n", nil
		}
		return "", nil
	}

	nd, err := AdoptKeenetic(run)
	if err != nil {
		t.Fatalf("AdoptKeenetic: %v", err)
	}
	if !strings.Contains(asked, "/opt/etc/dnsmasq.conf") {
		t.Errorf("the main config is where the upstreams live; it must be read: %q", asked)
	}
	if !strings.Contains(asked, "/opt/etc/dnsmasq.d/") {
		t.Errorf("and the conf-dir must still be read alongside it: %q", asked)
	}
	if i, j := strings.Index(asked, "dnsmasq.conf"), strings.Index(asked, "dnsmasq.d/"); i < 0 || j < i {
		t.Errorf("main config first, then the conf-dir — dnsmasq's own order: %q", asked)
	}
	if len(nd.Resolvers) != 2 {
		t.Fatalf("both upstreams must be adopted, got %d: %+v", len(nd.Resolvers), nd.Resolvers)
	}
	if !nd.StrictOrder {
		t.Error("strict-order lives in the main config and decides how upstreams are consulted")
	}
	if !nd.NoResolv {
		t.Error("no-resolv lives there too and decides whether resolv.conf is consulted at all")
	}
}

// TestAdoptKeeneticTagsTheFileEachUpstreamCameFrom (L5): provenance, because it decides what the
// write-back actually does.
//
// Every resolver was tagged "dnsmasq.d server". The write-back writes 00-upstream.conf INSIDE the
// conf-dir and never touches the main config, so an upstream that lives in the main config is not
// replaced by that write — it is duplicated beside it. Measured on a live Keenetic: the
// preview proposes strict-order, no-resolv, server=1.1.1.1 and server=8.8.8.8 while those four
// directives already sit in /opt/etc/dnsmasq.conf, and dnsmasq merges the conf-dir into it.
func TestAdoptKeeneticTagsTheFileEachUpstreamCameFrom(t *testing.T) {
	var asked string
	run := func(name string, args ...string) (string, error) {
		cmd := strings.Join(args, " ")
		if !strings.Contains(cmd, "dnsmasq") {
			return "", nil
		}
		asked = cmd
		// main config, sentinel, then the conf-dir — the shape the adopter's own command produces.
		return "server=1.1.1.1\n" + DnsmasqDirSentinel + "\nserver=9.9.9.9\n", nil
	}
	nd, err := AdoptKeenetic(run)
	if err != nil {
		t.Fatalf("AdoptKeenetic: %v", err)
	}
	// The adopter must EMIT the separator; without it the parser has nothing to switch on and every
	// upstream inherits the first file's tag — the defect, silently.
	if !strings.Contains(asked, DnsmasqDirSentinel) {
		t.Errorf("the read must separate the two files with the sentinel: %q", asked)
	}
	if len(nd.Resolvers) != 2 {
		t.Fatalf("both upstreams adopted, got %+v", nd.Resolvers)
	}
	if got := nd.Resolvers[0]; got.Address != "1.1.1.1" || got.Source != "dnsmasq.conf server" {
		t.Errorf("the main config's upstream must say so: %+v", got)
	}
	if got := nd.Resolvers[1]; got.Address != "9.9.9.9" || got.Source != "dnsmasq.d server" {
		t.Errorf("the conf-dir's upstream must say so: %+v", got)
	}
	// The sentinel is a comment: it must never surface as an upstream of its own.
	for _, r := range nd.Resolvers {
		if strings.Contains(r.Address, "wayhop-source") {
			t.Errorf("the sentinel leaked into the plane: %+v", r)
		}
	}
}
