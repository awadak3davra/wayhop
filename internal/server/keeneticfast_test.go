// A resolver whose upstreams did not answer before the install is not the install's to judge: the
// guard then requires dnsmasq's own answer only.
func TestKeeneticDNSGuardUpstreamOnlyWhenItWorkedBefore(t *testing.T) {
	useKeeneticDNSGuardFakes(t, true)
	fastDNSUpstream = func(context.Context) error { return errors.New("WAN down") }
	fake := &keeneticDNSGuardFake{}
	if err := reloadKeeneticDnsmasqGuarded(context.Background(), fake.run, func() error { return nil }, false); err != nil {
		t.Fatalf("guard failed on an upstream that was down before: %v", err)
	}
	if err := reloadKeeneticDnsmasqGuarded(context.Background(), fake.run, func() error { return nil }, true); err == nil {
		t.Fatal("guard passed without the upstream that worked before")
	}
}

// The back-out never removes the policy file: the previous one, or the installed one without its
// ipset= lines, which keeps the kill switch's fail-closed pins.
func TestKeeneticBackoutPolicyKeepsPins(t *testing.T) {
	installed := []byte("# Generated by WayHop\nipset=/a.example/wd_list_a_4,wd_list_a_6\n" +
		"# Kill switch: these names are resolved by the WayHop DNS listener only.\nserver=/a.example/127.0.0.1#5353\n")
	got := string(keeneticBackoutPolicy(keeneticPolicyFile{}, installed))
	if strings.Contains(got, "ipset=") || !strings.Contains(got, "server=/a.example/127.0.0.1#5353\n") {
		t.Fatalf("back-out without a previous file = %q", got)
	}
	// HUNT-K #4: the previous file lacks the pin the new plan added (and has one the new plan dropped):
	// the back-out keeps the previous mappings and takes the installed pins.
	prev := keeneticPolicyFile{content: []byte("ipset=/a.example/wr_list_a_4,wr_list_a_6\n" +
		"# Kill switch: these names are resolved by the WayHop DNS listener only.\nserver=/old.example/127.0.0.1#5353\n"), existed: true}
	want := "ipset=/a.example/wr_list_a_4,wr_list_a_6\n" +
		"# Kill switch: these names are resolved by the WayHop DNS listener only.\nserver=/a.example/127.0.0.1#5353\n"
	if got := string(keeneticBackoutPolicy(prev, installed)); got != want {
		t.Fatalf("back-out with a previous file = %q, want %q", got, want)
	}
}

type keeneticFastFakes struct {
	mu       sync.Mutex
	written  [][]byte
	restarts int
	alive    error
	// plane is what keeneticCurrentPlane answers (nil: the k a test passes in is current).
	plane *executionKernelArtifactV1
	// suspended is the fail-open flag; programs the plane programs run; disk the policy file on disk.
	suspended bool
	programs  []string
	disk      keeneticPolicyFile
}

func useKeeneticFastFakes(t *testing.T) (*Server, *keeneticFastFakes) {
	t.Helper()
	f := &keeneticFastFakes{}
	oldWrite, oldRestart, oldAlive, oldUp := writeKeeneticPolicy, keeneticDnsmasqRestart, fastDNSAlive, fastDNSUpstream
	oldFor, oldEvery, oldGuarded, oldResolve := fastDNSWatchFor, fastDNSWatchEvery, keeneticFastGuardedRestart, fastWarmResolve
	oldPresent, oldWait, oldPlane := keeneticDnsmasqServicePresent, keeneticDNSGuardWait, keeneticCurrentPlane
	oldSusp, oldClear, oldRun, oldRead := keeneticDNSSuspended, keeneticClearDNSOpen, keeneticRunPlaneProgram, readKeeneticPolicy
	t.Cleanup(func() {
		keeneticDNSSuspended, keeneticClearDNSOpen, keeneticRunPlaneProgram, readKeeneticPolicy = oldSusp, oldClear, oldRun, oldRead
		writeKeeneticPolicy, keeneticDnsmasqRestart, fastDNSAlive, fastDNSUpstream = oldWrite, oldRestart, oldAlive, oldUp
		fastDNSWatchFor, fastDNSWatchEvery, keeneticFastGuardedRestart, fastWarmResolve = oldFor, oldEvery, oldGuarded, oldResolve
		keeneticDnsmasqServicePresent, keeneticDNSGuardWait, keeneticCurrentPlane = oldPresent, oldWait, oldPlane
	})
	// The installed plane: the one the test set, else the one holding the runtime's installed file.
	keeneticCurrentPlane = func(s *Server) *executionKernelArtifactV1 {
		if f.plane != nil {
			return f.plane
		}
		s.fastDNS.mu.Lock()
		defer s.fastDNS.mu.Unlock()
		return &executionKernelArtifactV1{Ipset: &executionKernelIpsetArtifactV1{DnsmasqConf: s.fastDNS.keenetic.installed}}
	}
	fastWarmResolve = func(context.Context, string) {}
	keeneticDNSSuspended = func() bool { f.mu.Lock(); defer f.mu.Unlock(); return f.suspended }
	keeneticClearDNSOpen = func() { f.mu.Lock(); f.suspended = false; f.mu.Unlock() }
	keeneticRunPlaneProgram = func(_ context.Context, _ executionKernelIpsetArtifactV1, body string) error {
		f.mu.Lock()
		defer f.mu.Unlock()
		f.programs = append(f.programs, body)
		return nil
	}
	readKeeneticPolicy = func() (keeneticPolicyFile, error) { f.mu.Lock(); defer f.mu.Unlock(); return f.disk, nil }
	keeneticDnsmasqServicePresent = func() bool { return true }
	keeneticDNSGuardWait = 0
	writeKeeneticPolicy = func(p keeneticPolicyFile) error {
		f.mu.Lock()
		defer f.mu.Unlock()
		if !p.existed {
			f.written = append(f.written, nil)
			return nil
		}
		f.written = append(f.written, append([]byte(nil), p.content...))
		return nil
	}
	keeneticDnsmasqRestart = func(context.Context, *executionKernelIpsetArtifactV1) error {
		f.mu.Lock()
		f.restarts++
		f.mu.Unlock()
		return nil
	}
	fastDNSAlive = func(context.Context, bool) error {
		f.mu.Lock()
		defer f.mu.Unlock()
		return f.alive
	}
	fastDNSUpstream = func(context.Context) error { return nil }
	fastDNSWatchFor, fastDNSWatchEvery = 400*time.Millisecond, 20*time.Millisecond
	s := &Server{cfg: &config.Config{RoutingMode: "fast"}, platformOf: func() platform.Platform { return platform.Keenetic }}
	return s, f
}

// The watch backs out to the previous policy after three missed answers, a newer install ends an older
// install's watch, and the back-outs are bounded.
func TestKeeneticFastWatchBackoutGenerations(t *testing.T) {
	s, f := useKeeneticFastFakes(t)
	target := executionKernelIpsetArtifactV1{DnsmasqConf: []byte("ipset=/a.example/wd_list_a_4,wd_list_a_6\n")}
	prev := keeneticPolicyFile{content: []byte("ipset=/a.example/wr_list_a_4,wr_list_a_6\n"), existed: true}
	backedOut := func() bool {
		s.fastDNS.mu.Lock()
		defer s.fastDNS.mu.Unlock()
		return s.fastDNS.backedOut
	}

	// Healthy: nothing happens, and an unarmed install starts no watch at all.
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev, armed: true})
	time.Sleep(fastDNSWatchFor + 100*time.Millisecond)
	if backedOut() || len(f.written) != 0 {
		t.Fatalf("a healthy dnsmasq was backed out: %q", f.written)
	}
	f.mu.Lock()
	f.alive = errors.New("no answer")
	f.mu.Unlock()
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev, armed: false})
	time.Sleep(fastDNSWatchFor + 100*time.Millisecond)
	if backedOut() {
		t.Fatal("an unarmed install was watched")
	}

	// A replaced install's watch stops: the newer one (unarmed) is not backed out by the older.
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev, armed: true})
	time.Sleep(fastDNSWatchEvery / 2)
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev, armed: false})
	time.Sleep(fastDNSWatchFor + 100*time.Millisecond)
	if backedOut() {
		t.Fatal("an older install's watch backed out the newer one")
	}

	// Armed and stalled: backed out once, to the previous file, never to no file.
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev, armed: true})
	time.Sleep(fastDNSWatchFor + 100*time.Millisecond)
	f.mu.Lock()
	written, restarts := f.written, f.restarts
	f.mu.Unlock()
	if !backedOut() || len(written) != 1 || string(written[0]) != string(prev.content) || restarts != 1 {
		t.Fatalf("back-out wrote %q with %d restarts", written, restarts)
	}
	if !s.fastDNS.restartOwed {
		t.Error("a back-out that left dnsmasq silent owes no restart")
	}

	// Bounded: fastDNSMaxBackouts in a row end the retries until the next install.
	for i := 1; i < fastDNSMaxBackouts; i++ {
		s.keeneticFastBackout(context.Background(), s.fastDNSWatchGen(), "test stall")
	}
	if !s.fastDNS.gaveUp || !strings.Contains(s.fastDNS.err, "until the next Apply") {
		t.Fatalf("gaveUp=%v err=%s", s.fastDNS.gaveUp, s.fastDNS.err)
	}
	k := &executionKernelArtifactV1{Ipset: &target}
	s.fastDNS.retryAt = time.Time{}
	f.mu.Lock()
	f.alive = nil
	f.mu.Unlock()
	s.keeneticFastRestore(context.Background(), k)
	if !backedOut() {
		t.Fatal("restored after giving up")
	}
}

// After a back-out the installed policy is tried again, guarded; a plane installed since ends that.
func TestKeeneticFastRestore(t *testing.T) {
	s, f := useKeeneticFastFakes(t)
	target := executionKernelIpsetArtifactV1{DnsmasqConf: []byte("ipset=/a.example/wd_list_a_4,wd_list_a_6\n")}
	prev := keeneticPolicyFile{content: []byte("# previous\n"), existed: true}
	s.keeneticFastInstalled(target, keeneticFastPreInstall{before: prev})
	s.fastDNSNoteBackout(false, "stall", "%s %d", "stall")
	s.fastDNS.retryAt = time.Time{}
	guarded := 0
	keeneticFastGuardedRestart = func(context.Context, executionKernelIpsetArtifactV1, func() error, bool) error {
		guarded++
		return nil
	}
	other := executionKernelIpsetArtifactV1{DnsmasqConf: []byte("ipset=/b.example/wd_list_b_4,wd_list_b_6\n")}
	s.keeneticFastRestore(context.Background(), &executionKernelArtifactV1{Ipset: &other})
	if guarded != 0 || !s.fastDNS.backedOut {
		t.Fatal("a newer plane's file was overwritten by the old policy")
	}
	// HUNT-K #7: the tick read the old plane, but a newer one was installed before the lock was taken.
	f.plane = &executionKernelArtifactV1{Ipset: &other}
	s.keeneticFastRestore(context.Background(), &executionKernelArtifactV1{Ipset: &target})
	if guarded != 0 || len(f.written) != 0 {
		t.Fatalf("a stale retry wrote over the newer plane: guarded=%d written=%q", guarded, f.written)
	}
	// HUNT-K #8: a failed retry whose rollback left dnsmasq silent owes a restart.
	f.plane = &executionKernelArtifactV1{Ipset: &target}
	keeneticFastGuardedRestart = func(context.Context, executionKernelIpsetArtifactV1, func() error, bool) error {
		f.mu.Lock()
		f.alive = errors.New("silent")
		f.mu.Unlock()
		return errors.New("no answer")
	}
	s.keeneticFastRestore(context.Background(), &executionKernelArtifactV1{Ipset: &target})
	if !s.fastDNS.restartOwed || !s.fastDNS.backedOut {
		t.Fatalf("failed retry: restartOwed=%v backedOut=%v", s.fastDNS.restartOwed, s.fastDNS.backedOut)
	}
	f.mu.Lock()
	f.alive, f.written = nil, nil
	f.mu.Unlock()
	s.fastDNS.retryAt = time.Time{}
	keeneticFastGuardedRestart = func(context.Context, executionKernelIpsetArtifactV1, func() error, bool) error {
		guarded++
		return nil
	}
	s.keeneticFastRestore(context.Background(), &executionKernelArtifactV1{Ipset: &target})
	if guarded != 1 || s.fastDNS.backedOut || len(f.written) != 1 || string(f.written[0]) != string(target.DnsmasqConf) {
		t.Fatalf("restore: guarded=%d backedOut=%v written=%q", guarded, s.fastDNS.backedOut, f.written)
	}
}

// An Apply's reload: a refused dnsmasq --test puts the previous file back, records why for
// Diagnostics and fails the step; an accepted one arms the watch for the installed file.
func TestKeeneticFastReloadApplyStep(t *testing.T) {
	s, f := useKeeneticFastFakes(t)
	target := executionKernelIpsetArtifactV1{DynamicDomainSets: true, DnsmasqConf: []byte("ipset=/a.example/wd_list_a_4,wd_list_a_6\n")}
	plan := &pbr.Plan{Zones: []pbr.Zone{{Name: "list_a", Domains: []string{"a.example"}}}}
	const previous = "# previous\n"
	pre := keeneticFastPreInstall{before: keeneticPolicyFile{content: []byte(previous), existed: true}, armed: true, upstream: true}
	refuse := &keeneticDNSGuardFake{testErr: errors.New("bad option")}
	err := s.keeneticFastReload(context.Background(), refuse.run, target, plan, pre)
	if err == nil || !errors.Is(err, errExactProductionKernelApply) || refuse.restartSeen != 0 {
		t.Fatalf("refused test: err=%v restarts=%d", err, refuse.restartSeen)
	}
	if len(f.written) != 1 || string(f.written[0]) != previous || s.fastDNS.keenetic.guardErr == "" {
		t.Fatalf("refused test: written=%q guardErr=%q", f.written, s.fastDNS.keenetic.guardErr)
	}
	ok := &keeneticDNSGuardFake{}
	if err := s.keeneticFastReload(context.Background(), ok.run, target, plan, pre); err != nil {
		t.Fatal(err)
	}
	s.fastDNS.mu.Lock()
	defer s.fastDNS.mu.Unlock()
	if s.fastDNS.keenetic.guardErr != "" || string(s.fastDNS.keenetic.installed) != string(target.DnsmasqConf) ||
		string(s.fastDNS.keenetic.backout) != previous || s.fastDNS.restarted.IsZero() {
		t.Fatalf("accepted reload state: %+v", s.fastDNS.keenetic)
	}
}

// HUNT-K #9: an owed restart waits while an Apply holds applyMu (its own guarded restart is starting).
func TestOwedRestartWaitsForApply(t *testing.T) {
	s, restarts := func() (*Server, *int) { s, _, r := fastSyncServer(t); return s, r }()
	fastDNSAlive = func(context.Context, bool) error { return errors.New("silent") }
	s.fastDNS.restartOwed = true
	s.applyMu.Lock()
	s.fastDNSRestartOwed(context.Background())
	s.applyMu.Unlock()
	if *restarts != 0 {
		t.Fatalf("restarted %d time(s) during an Apply", *restarts)
	}
	s.fastDNSRestartOwed(context.Background())
	if *restarts != 1 {
		t.Fatalf("restarts after the Apply = %d, want 1", *restarts)
	}
}
