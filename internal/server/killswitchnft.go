// killswitchnft.go is the server's side of the nft plane's kill-switch guard (pbr/guard_nft.go): which
// names hold a plan is guarded with, the copy of the guard the router loads by itself at boot, the
// renewal of the hold while the core runs, and the flush of what was opened beside the core when it
// comes back. The learned addresses of kill-switched names are in killswitchnames.go.
//
// Boot. nft tables do not survive a reboot, and WayHop starts late (S95): for the seconds in between
// the firewall forwards the LAN to the provider with nothing of WayHop in the kernel. So the guard's
// program is also kept on flash, and a small init script WayHop writes loads it at S18, before the
// firewall (S19) and the network (S20) start. The guard names devices, sets and nothing else, so it
// loads with no interface up; a tunnel that comes up later is let through by its name. If the file is
// damaged the load fails and nothing else is affected: the guard is a table of its own, not a fw4
// include, so a bad file cannot keep the firewall from loading.
//
// What that holds at boot: the kill-switched addresses, until their tunnel is up (never by the
// provider); the addresses kill-switched names were reached at, from the learned file; and, when a
// kill switch covers names, every new connection from the LAN to the provider until the core runs,
// for at most the hold's period: the set's elements time out in the kernel, so a WayHop that never
// starts cannot keep the LAN offline.
//
// The loader does nothing on a router where WayHop is not installed or not enabled: a
// guard loaded at every boot with no WayHop to route the lists it holds would drop them for good.

const (
	// ksNamesHoldMin keeps the hold standing between two renewals (the reconcile tick, 30 s).
	ksNamesHoldMin = 120
	// ksLegacyCoreTun matches the core's TUN for a plan whose config does not state the device's name
	// (generated before WayHop pinned it, or by an override that left it out): the core then takes
	// the first free tunN. A plan generated by this build names the device (pbr.Plan.CoreTun, read
	// from the generated config) and the guard passes exactly that one.
	ksLegacyCoreTun = "tun*"
)

// The boot copy, the learned addresses beside it, and their loader. Variables so tests write into a
// temporary directory.
var (
	ksBootGuardFile   = "/etc/wayhop/ks-guard.nft"
	ksBootLearnedFile = "/etc/wayhop/ks-learned.nft"
	ksBootGuardInit   = "/etc/init.d/wayhop-guard"
	ksBootGuardEnable = "/etc/rc.d/S18wayhop-guard"
)

// ksBootGuardScript is the init script that loads the boot copy. Nothing in it depends on the
// daemon running, the network or the firewall. The two paths it tests are the package's
// (packaging/openwrt/wayhop.init: PROG and START); a test holds them together.
const ksBootGuardScript = `#!/bin/sh /etc/rc.common
# Written by WayHop: loads the kill switch guard before the firewall and the network start.
# Removed with the guard; do not edit. See /etc/wayhop/ks-guard.nft.
# shellcheck disable=SC2034
START=18

start() {
	# Only for a WayHop that will start at this boot. Stopped for good (service wayhop disable),
	# removed, or its binary lost: nothing would route the lists the guard holds, so it stays out.
	[ -x /usr/sbin/wayhop ] && [ -e /etc/rc.d/S95wayhop ] || return 0
	[ -s /etc/wayhop/ks-guard.nft ] || return 0
	nft -f /etc/wayhop/ks-guard.nft 2>&1 | logger -t wayhop-guard
	# The addresses kill-switched names were reached at. Its own transaction: a file that does not
	# fit the guard is refused as a whole and the guard stands without it.
	[ -s /etc/wayhop/ks-learned.nft ] && nft -f /etc/wayhop/ks-learned.nft 2>&1 | logger -t wayhop-guard
	return 0
}
`

// namesHold is what a plan's guard is told about names (pbr.NamesHold).
//
// The broad hold is armed only in hybrid mode: there everything the kernel plane does not route by
// address goes through the core's TUN, so "forwarded straight to the provider" is exactly "the core
// is not carrying it". In fast mode the provider is where unlisted traffic belongs, and a broad hold
// would stop the LAN; the learned addresses of kill-switched names are held there all the same,
// and may leave by a tunnel only.
//
// With it travels what the guard is told about the router's own routes (killswitchlocal.go), which
// has nothing to do with names: every plan gets it.
func (s *Server) namesHold(plan *pbr.Plan) pbr.NamesHold {
	if s == nil || plan == nil {
		return pbr.NamesHold{}
	}
	hold := s.namesHoldOnly(plan)
	hold.Local, hold.LocalPartial, hold.Provider = s.guardLocalState()
	hold.Source = s.guardSources()
	return hold
}

func (s *Server) namesHoldOnly(plan *pbr.Plan) pbr.NamesHold {
	if !plan.GuardNames {
		return pbr.NamesHold{}
	}
	cfg := s.config()
	if s.routingMode(cfg) != "hybrid" {
		return pbr.NamesHold{Pass: append([]string(nil), plan.MasqIfaces...)}
	}
	seconds := ksBootHoldLift(cfg)
	switch {
	case seconds == 0:
		seconds = -1 // kill_switch_boot_hold_lift < 0: never lifted by time
	case seconds < ksNamesHoldMin:
		seconds = ksNamesHoldMin
	}
	tun := plan.CoreTun
	if tun == "" {
		tun = ksLegacyCoreTun
	}
	// The hold covers IPv6 only when the core's TUN carries it: beside an IPv4-only
	// TUN the LAN's IPv6 passes the core whether it runs or not, and a hold renewed while the core
	// runs would drop all of it for as long as WayHop is healthy.
	return pbr.NamesHold{Seconds: seconds, Pass: append([]string{tun}, plan.MasqIfaces...), V6: plan.CoreTunV6}
}

// ksStoredPlanOnce says once per run that the installed plan predates the learned addresses.
var ksStoredPlanOnce sync.Once

// noteStoredPlan logs, once, that a kill switch over names runs on a plan an earlier build applied:
// such a plan names no learned-address sets and no TUN device, so nothing is noted
// for the names and the hold covers IPv4 only until the operator applies again. Review says the
// same; the log says it to whoever does not open Review after an upgrade.
func (s *Server) noteStoredPlan(plan *pbr.Plan) {
	if plan == nil || !plan.GuardNames || plan.CoreTun != "" && len(plan.GuardNameSets) > 0 {
		return
	}
	if s.routingMode(s.config()) != "hybrid" {
		return
	}
	ksStoredPlanOnce.Do(func() {
		log.Printf("kill switch: the installed plan was applied by an earlier build: until the next Apply no addresses are noted for " +
			"kill-switched names and the names hold covers IPv4 only. Apply once.")
	})
}

// nftGuardProgram is the guard as the adapter loads it for plan, marker included; "" for none.
func (s *Server) nftGuardProgram(plan *pbr.Plan) string {
	if plan == nil {
		return ""
	}
	guard := plan.RenderNftGuardWith(s.namesHold(plan))
	if guard == "" {
		return ""
	}
	return guard + pbr.GuardProofProgram(guard)
}

// syncBootGuard makes the boot copy say what the installed plan's guard says: written when it
// differs, removed (with its loader and the learned file) when the plan has no guard. plan nil = no
// plane. Failures are logged, never returned: the running guard is in place either way, and the next
// tick tries again.
func (s *Server) syncBootGuard(plan *pbr.Plan) {
	if s == nil || s.config().Demo || s.detectedPlatform() != platform.OpenWrt {
		return
	}
	program := s.nftGuardProgram(plan)
	if program == "" {
		s.ksLearn.Store(nil) // no guard, no sets to learn into
		for _, p := range []string{ksBootGuardEnable, ksBootGuardInit, ksBootGuardFile, ksBootLearnedFile} {
			if err := os.Remove(p); err != nil && !os.IsNotExist(err) {
				log.Printf("kill switch: remove %s: %v", p, err)
			}
		}
		return
	}
	if err := writeIfChanged(ksBootGuardFile, []byte(program), 0o600); err != nil {
		log.Printf("kill switch: the boot copy of the guard was not written (the guard holds from WayHop's start, not from boot): %v", err)
		return
	}
	// The learned file must fit the guard it is loaded into: nft refuses a whole file for one set
	// the table does not have.
	s.syncLearnedFile(plan)
	if err := writeIfChanged(ksBootGuardInit, []byte(ksBootGuardScript), 0o755); err != nil {
		log.Printf("kill switch: the boot loader of the guard was not written: %v", err)
		return
	}
	if _, err := os.Lstat(ksBootGuardEnable); err != nil {
		if err := os.Symlink("../init.d/"+filepath.Base(ksBootGuardInit), ksBootGuardEnable); err != nil && !os.IsExist(err) {
			log.Printf("kill switch: the boot loader of the guard was not enabled: %v", err)
		}
	}
}

// writeIfChanged leaves a file that already says this alone (atomicfile.Write compares first): the
// reconcile tick calls it every 30 s and must not wear the flash.
func writeIfChanged(path string, data []byte, mode os.FileMode) error {
	return atomicfile.Write(path, data, mode)
}

// renewNamesHold gives the hold another period while the core runs. Not while it does not: a core
// that stays down lets the hold run out, which is the bound the operator was promised. run loads an
// nft program.
func (s *Server) renewNamesHold(ctx context.Context, plan *pbr.Plan, coreRunning bool, run func(context.Context, string) error) {
	hold := s.namesHold(plan)
	if hold.Seconds <= 0 || len(hold.Pass) == 0 || !coreRunning {
		return // no hold, or a strict one whose elements never time out
	}
	if err := run(ctx, pbr.RenderGuardHoldRenew(hold.Seconds)); err != nil {
		log.Printf("kill switch: the names hold was not renewed (it stands for what is left of its %d s): %v",
			hold.Seconds, strings.TrimSpace(err.Error()))
	}
}

// The core as the reconcile tick last saw it.
const (
	ksCoreUnseen int32 = iota
	ksCoreUp
	ksCoreDown
)

// ksLANPrefixes is the home network's own subnets; tests replace it.
var ksLANPrefixes = func(s *Server) []netip.Prefix {
	lans, _ := s.lanPrefixes()
	return lans
}

// ksDirectNoLAN says once per run that the LAN's own subnets could not be read.
var ksDirectNoLAN sync.Once

// coreReturned is called on every reconcile tick with whether the core runs. When it runs and did
// not at the tick before (or this is the daemon's first look), the flows the LAN opened straight
// to the provider in between are removed: the core's redirect takes new connections
// only, and an offloaded flow never reaches the guard's hook, so a connection to a kill-switched
// name opened while the names hold had lapsed stayed on the provider until it ended.
//
// Hybrid mode with a kill switch over names only: there the core carries everything the kernel
// plane does not, so "opened beside the core" is well defined; anywhere else the provider is where
// such a flow belongs.
func (s *Server) coreReturned(plan *pbr.Plan, running bool) {
	state := ksCoreDown
	if running {
		state = ksCoreUp
	}
	was := s.ksCoreSeen.Swap(state)
	if !running || was == ksCoreUp || plan == nil || !plan.GuardNames {
		return
	}
	cfg := s.config()
	if cfg.Demo || s.routingMode(cfg) != "hybrid" {
		return
	}
	lans := ksLANPrefixes(s)
	if len(lans) == 0 {
		ksDirectNoLAN.Do(func() {
			log.Printf("kill switch: connections opened while the core was down are left to end on their own: the home network's subnets could not be read")
		})
		return
	}
	t, err := ctflushOpen()
	if err != nil {
		return // resetUnavailableFindings and offloadFindings say so in Review
	}
	defer t.Close()
	isLAN := func(a netip.Addr) bool {
		for _, p := range lans {
			if p.Contains(a) {
				return true
			}
		}
		return false
	}
	res, err := ctflush.FlushDirect(t, plan, ctflush.Options{Limit: ctflushLimit, Local: ctflushLocal()},
		ctflush.Direct{CoreMark: generator.AutoRedirectInputMark, LAN: isLAN, V6: plan.CoreTunV6})
	switch {
	case err != nil:
		log.Printf("kill switch: connections opened while the core was down: %d reset, then stopped: %v", res.Deleted, err)
	case res.Deleted > 0:
		log.Printf("kill switch: the core is back: %d connection(s) opened beside it were reset (%d examined)", res.Deleted, res.Seen)
	}
}
