// i18n-generate.mjs — build the shipped dictionaries from the tracked source. ONE command, and it
// runs from a fresh clone.
//
// It replaces a pipeline that could not: the source of truth used to live in `.claude/i18n/dicts/`,
// which is a dev-only directory excluded from the published tree, and `web/dist/i18n.js` announced
// itself as generated from files nobody outside this machine had. A public clone could read the
// dictionaries and never regenerate them. The source now lives in `web/i18n/`, beside the code that
// ships it.
//
// It also stops emitting the 2.1 MB monolith. index.html loads `i18n-meta.js` + `i18n-loader.js`,
// and the loader pulls exactly one `i18n/<lang>.js`; the monolith was embedded into the binary by
// `//go:embed dist` and served to nobody — 2.1 MB of a ~60 MB router overlay spent on a file the
// browser never requests.
//
//   node scripts/i18n-generate.mjs [--check]
//
// --check regenerates into memory and fails if the tree differs, which is what CI runs: it makes
// "the committed dictionaries are what the source produces" a fact rather than a hope.
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'web/i18n';
const OUT = 'web/dist/i18n';
const META = 'web/dist/i18n-meta.js';
const LANGS = path.join(SRC, 'langs.json');
const CHECK = process.argv.includes('--check');

if (!fs.existsSync(LANGS)) {
  console.error(`${LANGS} is missing — it declares the language list and RTL set, and without it the `
    + 'generated meta would silently drop languages the panel offers.');
  process.exit(1);
}
const meta = JSON.parse(fs.readFileSync(LANGS, 'utf8'));
if (!Array.isArray(meta.langs) || !Array.isArray(meta.rtl)) {
  console.error(`${LANGS} must hold {"langs": [...], "rtl": [...]}`);
  process.exit(1);
}

const dicts = fs.readdirSync(SRC).filter((f) => f.endsWith('.json') && f !== 'langs.json').sort();
// The floor is a COUNT, and the count changed: the panel used to ship 15 languages and now ships 10
// (auto/en plus 9 dictionaries). The CIS-and-Europe set is what the operator asked for — the CJK,
// Indic and Middle-Eastern dictionaries were removed rather than left untranslated, because a
// language in the picker that nobody maintains is a promise the panel cannot keep. The guard stays
// so a generator run that silently emits fewer than the tracked sources cannot quietly drop one.
const EXPECTED_DICTS = 9;
if (dicts.length < EXPECTED_DICTS) {
  console.error(`${SRC} holds ${dicts.length} dictionary file(s); the panel ships ${EXPECTED_DICTS + 1} `
    + 'languages and a generator that quietly emits fewer would remove them from the UI.');
  process.exit(1);
}

// Every language the meta offers (beyond auto/en, which have no dictionary) must have a source file.
// Without this a language stays in the picker and resolves to nothing.
const offered = meta.langs.map((l) => l.code).filter((c) => c !== 'auto' && c !== 'en');
const have = dicts.map((f) => f.slice(0, -5));
const missing = offered.filter((c) => !have.includes(c));
if (missing.length) {
  console.error(`langs.json offers ${missing.join(', ')} but ${SRC} has no dictionary for them`);
  process.exit(1);
}

const banner = (what) => `/* Generated by scripts/i18n-generate.mjs from web/i18n/ — DO NOT EDIT.\n * ${what} */\n`;

const files = new Map();
files.set(META,
  banner('Language metadata + the shared WR_DICTS object. Always loaded; the per-language dictionary\n'
    + ' * (i18n/<lang>.js) is loaded separately and fills this object in place, so only ONE language is\n'
    + ' * ever downloaded (see the index.html bootstrap).')
  + 'window.WR_DICTS = window.WR_DICTS || {};\n'
  + `window.WR_LANGS = ${JSON.stringify(meta.langs)};\n`
  + `window.WR_RTL = ${JSON.stringify(meta.rtl)};\n`);

for (const f of dicts) {
  const lang = f.slice(0, -5);
  const d = JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
  const keys = Object.keys(d);
  if (!keys.length) { console.error(`${SRC}/${f} is empty`); process.exit(1); }
  // Same object shape the previous split emitted, so the loader and app.js are untouched.
  const body = keys.map((k) => `${JSON.stringify(k)}: ${JSON.stringify(d[k])}`).join(', ');
  files.set(path.join(OUT, `${lang}.js`),
    banner(`${lang} dictionary (${keys.length} keys). Fills window.WR_DICTS in place.`)
    + 'window.WR_DICTS = window.WR_DICTS || {};\n'
    + `window.WR_DICTS[${JSON.stringify(lang)}] = {${body}};\n`);
}

if (CHECK) {
  const drift = [];
  for (const [p, want] of files) {
    const got = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (got !== want) drift.push(p + (got === null ? ' (missing)' : ' (differs)'));
  }
  // A stale file left behind is drift too: a language removed from source must leave the tree.
  for (const f of fs.existsSync(OUT) ? fs.readdirSync(OUT) : []) {
    if (!files.has(path.join(OUT, f))) drift.push(`${OUT}/${f} (not produced by the source)`);
  }
  if (drift.length) {
    console.error(`i18n generate --check: ${drift.length} file(s) differ from what web/i18n/ produces:`);
    for (const d of drift.slice(0, 20)) console.error(`  ${d}`);
    console.error('Run `node scripts/i18n-generate.mjs` and commit the result.');
    process.exit(1);
  }
  console.log(`i18n generate --check: ${files.size} generated file(s) match web/i18n/ exactly`);
  process.exit(0);
}

fs.mkdirSync(OUT, { recursive: true });
for (const [p, body] of files) fs.writeFileSync(p, body, 'utf8');
for (const f of fs.readdirSync(OUT)) {
  if (!files.has(path.join(OUT, f))) { fs.rmSync(path.join(OUT, f)); console.log(`  removed stale ${OUT}/${f}`); }
}
let total = 0, biggest = ['', 0];
for (const [p] of files) {
  const n = fs.statSync(p).size;
  total += n;
  if (p !== META && n > biggest[1]) biggest = [path.basename(p, '.js'), n];
}
console.log(`wrote ${files.size} file(s), ${total} bytes total`);
console.log(`a visitor downloads meta + one language: ${fs.statSync(META).size + biggest[1]} bytes worst case ("${biggest[0]}")`);
